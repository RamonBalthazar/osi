// Order modes are shown in.
const MODE_ORDER: Mode[] = ["underground", "overground", "elizabeth", "dlr", "national-rail"];

export interface StationLines {
  modes: Mode[];
  lines: Line[];
}

export function stationLines(name: string): StationLines {
  const served = STATION_LINES[name] ?? [];
  const lines = served.filter((s): s is LineId => s !== "nr").map((id) => LINES[id]);
  const modes = new Set<Mode>(lines.map((l) => l.mode));
  if (served.includes("nr")) modes.add("national-rail");
  return {
    modes: MODE_ORDER.filter((m) => modes.has(m)),
    lines,
  };
}
